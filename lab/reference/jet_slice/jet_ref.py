def run_trajectory(seed):
    T = {k: (fx(v) if isinstance(v, str) else v) for k, v in TP.items()}
    a, site = TP["actor"], TP["site"]
    pu = next_u64(seed, 0, SYS_AI, a, 0)
    profile = draw_profile(pu)
    prof = PROFILES[profile]
    clusters = ["CHEM", "MET"]
    R = {("MET", "CHEM"): T["R_MET_CHEM"], ("CHEM", "MET"): T["R_MET_CHEM"]}
    H, M = {}, {}
    for c, hc in [("MET", TP["H_MET"]), ("CHEM", TP["H_CHEM"])]:
        h, m = site_dims(hc)
        for d in DIMS:
            H[(c, d)], M[(c, d)] = h[d], m[d]
    M_inv = {k: mul(T["delta_M"], m) for k, m in M.items()}
    X = {p: fx(TP["X0"].get(p, "0")) for p in NODES if NODES[p]["type"] == "PRC"}
    known = set(KNOWN_AT_START)
    prog = {n: ZERO for n in NODES if n not in known}
    K_d = {k: fx(v) for k, v in TP["K_d0"].items()}
    K_ind = {k: ZERO for k in K_d}
    # service columns "last month" (contract 4.0); fixture: no output in month -1
    proc_v = {p: ZERO for p in X}
    proc_yield = {p: ZERO for p in X}
    budget = T["budget0"]
    g_month = div(T["g"], fi(12))

    def j_for_year(year):
        res = {}
        for n in sorted(NODES):
            u = next_u64(seed, 12 * year, SYS_PRIO_J, a * 64 + n, 0)
            res[n] = {"u": u, "j": draw_j(u)}
        return res

    def yield_of(p):
        nd = NODES[p]
        return yield_p({"prc_id": p, "req": {d: fx(v) for d, v in zip(DIMS, nd["req"])},
                        "H": {d: H[(nd["cluster"], d)] for d in DIMS},
                        "M": {d: M[(nd["cluster"], d)] for d in DIMS},
                        "X": X[p], "Xh": fx(TP["Xh"][nd["tier"]]), "lam0": T["lam0"], "l_lic": None})["yield"]

    # setup = AI decision of tick 0 applied at tick 0 (A8)
    shares = tuple(fx(s) for s in prof["shares"])
    jmap = j_for_year(0)
    rate = {p: (fx(NODES[p]["rate"]) if (p in known and yield_of(p) > 0) else ZERO) for p in X}
    pending = []
    rows = []
    setup = {"profile_key": [seed, 0, SYS_AI, a, 0], "profile_u": pu, "profile": prof["name"],
             "shares": list(shares), "j_year0": {str(n): v for n, v in jmap.items()},
             "rate": {str(p): v for p, v in rate.items()}}

    # Daily loop (decision #60): day tick `day`; monthly systems fire on day 1 of a month, t = month index.
    # On other days no slice system is due and the state is unchanged (clock only), so this loop
    # gives exactly the month-step results; RNG keys use the month index t, not the day tick (spec 9.1).
    for day in range(day_tick(TP["ticks"])):
        t = month_fired_at(day)
        if t is None:
            continue
        # ---- start of month step t: exogenous budget, then commands computed at month t-1
        if t > 0:
            budget = mul(budget, ONE + g_month)
        applied = []
        for cmd in pending:
            if cmd["cmd"] == "set_rate":
                rate[cmd["prc"]] = cmd["value"]
            elif cmd["cmd"] == "set_year":
                jmap = cmd["j"]
            applied.append({k: v for k, v in cmd.items() if k != "j"})
        pending = []
        # ---- compute (reads the snapshot only)
        snap_known = set(known)
        S = mul(shares[0], budget)
        frontier = [n for n in sorted(NODES) if n not in snap_known
                    and all(r in snap_known for r in NODES[n]["requires"])]
        wraw = {n: mul(PROFILES[profile]["prio"](NODES[n]), jmap[n]["j"]) for n in frontier}
        wsum = add(*wraw.values()) if wraw else ZERO
        know_rows, discoveries, dK = [], [], {k: ZERO for k in K_d}
        spent = ZERO
        for n in frontier:
            nd = NODES[n]
            w_n = div(wraw[n], wsum)
            alloc = mul(S, w_n)
            spent = add(spent, alloc)
            disc = nd["disc"]
            Kmix = ZERO if disc is None else (add(K_d[disc], K_ind[disc]) if nd["type"] in ("ENG", "PRC") else K_d[disc])
            c_money = mul(fx(nd["c_n"]), mul(fi(12), T["S_ref"]))
            ce = c_eff(c_money, T["k_diff"], False, T["k_K"], Kmix, T["K_ref"], [])
            dprog = div(alloc, ce)
            p_new = add(prog[n], dprog)
            krow = {"node": n, "w": w_n, "alloc": alloc, "Kmix": Kmix, "c_eff": ce, "dprog": dprog}
            if nd["hazard"]:
                p_new = min(p_new, T["prog_cap"])
                u = next_u64(seed, t, SYS_KNOW, a * 64 + n, 0)
                hz = hazard(p_new, T["theta_start"], T["h_max"], T["y_half"], u)
                krow["hazard"] = {"key": [seed, t, SYS_KNOW, a * 64 + n, 0], "h": hz["h"],
                                  "u": u if hz["active"] else None,
                                  "threshold": hz["check"]["threshold"] if hz["active"] else None,
                                  "opened": hz["opened"]}
                opened = hz["opened"]
            else:
                opened = p_new >= ONE
            krow["prog_new"] = p_new
            prog[n] = p_new                  # written to own buffer; nobody reads it this tick
            if opened:
                discoveries.append((a, n))
            if disc is not None:
                dK[disc] = add(dK[disc], alloc)
            know_rows.append(krow)
        # K_ind (contract 4.0/4.3, A10): knowledge compute from the snapshot (proc_v, proc_yield of t-1,
        # K_d, K_ind); own buffer, visible from t+1. c_eff above used the snapshot K_ind.
        K_ind_new = {}
        for d in sorted(K_ind):
            V_d = add(*[proc_v[p] for p in sorted(proc_v)
                        if NODES[p]["disc"] == d and proc_yield[p] >= fx("0.3")]) if proc_v else ZERO
            K_ind_new[d] = k_ind_step(K_ind[d], K_d[d], V_d, T["eta"], T["V_ref"], T["theta_ind"], T["delta_ind"])["K_ind_new"]
        # industry compute: yield from snapshot culture/tooling/experience -> proc_yield buffer; rate in force
        reports, yields = [], {}
        for p in sorted(X):
            yields[p] = yield_of(p) if p in snap_known else ZERO
            if p in snap_known and rate[p] > 0 and yields[p] > 0:
                reports.append((site, p, rate[p], mul(rate[p], fx(NODES[p]["labour"]))))
        # industry compute: culture_H (contract 4.0/4.1, A3) from snapshot H and proc_v of month t-1
        H_new, M_new, culture_detail = {}, {}, {}
        for c in clusters:
            for d in DIMS:
                procs = [{"prc_id": p, "v": proc_v[p], "r_d": fx(NODES[p]["req"][DIMS.index(d)]), "world_lead": False}
                         for p in sorted(proc_v) if proc_v[p] > 0 and NODES[p]["cluster"] == c]
                spill_in = [{"cluster": c2, "R": R[(c, c2)], "H_other": H[(c2, d)]} for c2 in clusters if c2 != c]
                res = culture_step(culture_base(H=H[(c, d)], procs=procs, spill_in=spill_in,
                                                alpha=T["alpha"], delta_H=T["delta_H"], rho_max=T["rho_max"],
                                                k_catch=T["k_catch"], sigma=T["sigma"], phi_floor=T["phi_floor"],
                                                Hcap=T["Hcap"], act=T["act"], w=T["w"]))
                H_new[(c, d)] = res["H_new"]
                culture_detail["%s.%s" % (c, d)] = {"V_c": res["V_c"], "dH_plus": res["dH_plus"],
                                                     "dH_minus": res["dH_minus"]}
                # spec 3.2, 3.5 A11: dM = invest/cost_M - delta_M*M (industry compute, snapshot M);
                # fixture: cost_M = 1, invest = delta_M*M0
                M_new[(c, d)] = add(M[(c, d)], div(M_inv[(c, d)], T["cost_M"]), -mul(T["delta_M"], M[(c, d)]))
        # AI commands for t+1
        for p in sorted(X):
            want = fx(NODES[p]["rate"]) if (p in snap_known and yields[p] > 0) else ZERO
            if want != rate[p]:
                pending.append({"cmd": "set_rate", "prc": p, "value": want, "decided_at": t, "applies_at": t + 1})
        if t > 0 and t % 12 == 0:
            pending.append({"cmd": "set_year", "year": t // 12, "j": j_for_year(t // 12),
                            "decided_at": t, "applies_at": t + 1})
        # ---- merge (contract 4.0): report_output by (site, prc) -> proc_X, proc_v; discoveries by (actor, node); K_d
        reports.sort(key=lambda r: (r[0], r[1]))
        got = set()
        for (_, p, units, labour) in reports:
            X[p] = add(X[p], units)
            proc_v[p] = labour
            got.add(p)
        for p in sorted(X):
            if p not in got:
                proc_v[p] = ZERO
                X[p] = X[p] - mul(T["delta_X"], X[p])
        discoveries.sort()
        for (_, n) in discoveries:
            known.add(n)
        for d in sorted(K_d):
            amount = dK[d]
            opened_d = sum(1 for (_, n) in discoveries if NODES[n]["disc"] == d)
            K_d[d] = add(K_d[d], div(mul(T["mu_K"], amount), T["S_ref"]), mul(T["k_node"], fi(opened_d)))
        # end of tick: compute buffers become state (visible from t+1)
        H_snap = dict(H)
        H.update(H_new)
        M.update(M_new)
        K_ind = K_ind_new
        proc_yield = dict(yields)
        # ---- post: invariants only (contract 4.0)
        # post invariants (README I1-I6), checked on the reference itself
        assert spent <= S <= budget
        H_floor = mul(T["phi_floor"], T["Hcap"])
        for k in H:
            assert ZERO <= H[k] and H[k] - H_snap[k] <= T["rho_max"] + 1
            assert H[k] >= min(H_snap[k], H_floor)
        assert all(ZERO <= y <= ONE for y in yields.values())
        assert all(prog[n] <= T["prog_cap"] for n in prog if NODES[n]["hazard"])
        assert all(r in known for n in known for r in NODES[n]["requires"])
        rows.append({
            "tick": t, "day_tick": day, "date": iso(day), "budget": budget, "S_R": S, "spent_R": spent, "commands_applied": applied,
            "frontier": frontier, "knowledge": know_rows,
            "merge_report_output": [list(r) for r in reports],
            "merge_discoveries": [list(dd) for dd in discoveries],
            "commands_issued": [{k: val for k, val in c.items() if k != "j"} for c in pending],
            "yield_used": {str(p): yields[p] for p in sorted(yields)},
            "rate_in_force": {str(p): rate[p] for p in sorted(rate)},
            "state_after": {
                "known": sorted(known), "prog": {str(n): prog[n] for n in sorted(prog)},
                "K_d": dict(sorted(K_d.items())), "K_ind": dict(sorted(K_ind.items())),
                "culture_H": {"%s.%s" % k: H[k] for k in sorted(H)},
                "tooling_M": {"%s.%s" % k: M[k] for k in sorted(M)},
                "proc_X": {str(p): X[p] for p in sorted(X)},
                "proc_v": {str(p): proc_v[p] for p in sorted(proc_v)},
                "proc_yield": {str(p): proc_yield[p] for p in sorted(proc_yield)},
            },
            "culture_detail": culture_detail,
        })
    return setup, rows


def coverage(rows):
    hz_checks = [k["hazard"] for r in rows for k in r["knowledge"] if "hazard" in k and k["hazard"]["u"] is not None]
    return {
        "hazard_miss_before_hit": any(not h["opened"] for h in hz_checks) and any(h["opened"] for h in hz_checks),
        "app_opened": any([0, 5] in r["merge_discoveries"] for r in rows),
        "two_reports_one_tick": any(len(r["merge_report_output"]) >= 2 for r in rows),
        "rate_command_t_plus_1": any(c["cmd"] == "set_rate" for r in rows for c in r["commands_issued"]),
        "year_command": any(c["cmd"] == "set_year" for r in rows for c in r["commands_issued"]),
        "multi_discovery_tick": any(len(r["merge_discoveries"]) >= 2 for r in rows),
    }


# ================================================================ output
def dumps(obj):
    return json.dumps(obj, sort_keys=True, indent=1, ensure_ascii=True) + "\n"


def trajectory_csv(rows):
    cols = ["tick", "budget", "S_R", "known", "prog_1", "prog_2", "prog_3", "prog_4", "prog_5",
            "K_d_metal", "K_d_prop", "K_ind_metal", "X_4", "X_6", "rate_4", "rate_6", "yield_4", "yield_6",
            "H_MET_precision", "H_MET_purity", "H_MET_quality_control", "H_CHEM_purity", "discoveries"]
    lines = [",".join(cols)]
    for r in rows:
        s = r["state_after"]
        vals = [str(r["tick"]), dec(r["budget"]), dec(r["S_R"]), "|".join(map(str, s["known"]))]
        vals += [dec(s["prog"][str(n)]) for n in range(1, 6)]
        vals += [dec(s["K_d"]["metal"]), dec(s["K_d"]["prop"]), dec(s["K_ind"]["metal"]),
                 dec(s["proc_X"]["4"]), dec(s["proc_X"]["6"]), dec(r["rate_in_force"]["4"]), dec(r["rate_in_force"]["6"]),
                 dec(r["yield_used"]["4"]), dec(r["yield_used"]["6"]),
                 dec(s["culture_H"]["MET.precision"]), dec(s["culture_H"]["MET.purity"]),
                 dec(s["culture_H"]["MET.quality_control"]), dec(s["culture_H"]["CHEM.purity"]),
                 "|".join("%d:%d" % tuple(d) for d in r["merge_discoveries"])]
        lines.append(",".join(vals))
    return "\n".join(lines) + "\n"


TRAJ_SEED = 6   # chosen by --find-seed for coverage (README); fixed afterwards
FORMULA_SEED = 20261103


def build():
    for v in RNG_VECTORS:
        assert next_u64(*v[:5]) == v[5], "CounterRng port mismatch"
    import datetime
    base = datetime.date(*START_DATE)
    for d in range(0, 12000, 7):
        assert iso(d) == (base + datetime.timedelta(days=d)).isoformat(), "calendar mismatch"
    assert day_tick(360) == 10957 and day_tick(384) == 11688, "horizon in days"
    assert all(month_fired_at(day_tick(m)) == m for m in range(385))
    assert sum(month_fired_at(d) is not None for d in range(day_tick(384))) == 384
    setup, rows = run_trajectory(TRAJ_SEED)
    cov = coverage(rows)
    traj = {"schema": "jet_slice_reference_trajectory/1", "fx6_scale": SCALE, "seed": TRAJ_SEED,
            "params": TP | {"Xh": {str(k): v for k, v in TP["Xh"].items()}, "X0": {str(k): v for k, v in TP["X0"].items()}},
            "nodes": {str(k): {kk: vv for kk, vv in v.items()} for k, v in NODES.items()},
            "known_at_start": KNOWN_AT_START, "setup": setup, "rows": rows, "coverage": cov,
            "calendar": {"start_date": iso(0), "fire_day": FIRE_DAY, "days": day_tick(TP["ticks"]),
                         "idle_days": day_tick(TP["ticks"]) - TP["ticks"]}}
    form = {"schema": "jet_slice_reference_formulas/1", "fx6_scale": SCALE, "seed": FORMULA_SEED,
            **formula_cases(FORMULA_SEED), "calendar": calendar_cases()}
    return {"formulas.json": dumps(form), "trajectory.json": dumps(traj), "trajectory.csv": trajectory_csv(rows)}, cov


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--find-seed", action="store_true")
    args = ap.parse_args()
    if args.find_seed:
        for s in range(1, 200):
            _, rows = run_trajectory(s)
            if all(coverage(rows).values()):
                print(s)
                return 0
        print("none")
        return 1
    files, cov = build()
    outdir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")
    bad = [k for k, v in cov.items() if not v]
    if args.check:
        diff = []
        for name, text in files.items():
            path = os.path.join(outdir, name)
            if not os.path.exists(path) or open(path, encoding="ascii").read() != text:
                diff.append(name)
        print("check:", "OK" if not diff and not bad else "DIFF %s uncovered %s" % (diff, bad))
        return 1 if diff or bad else 0
    os.makedirs(outdir, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(outdir, name), "w", encoding="ascii", newline="\n") as f:
            f.write(text)
        print("%s sha256=%s" % (name, hashlib.sha256(text.encode()).hexdigest()))
    print("coverage:", cov)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
