using System.Globalization;
using System.Text;
using NetTopologySuite.Geometries;
using NetTopologySuite.Operation.Overlay;
using NetTopologySuite.Operation.OverlayNG;

namespace Singularity.MapBuilder;

/// <summary>
/// One-time (and incremental) helper that writes spec files (ADR-0011 §1, §2.2): merges of small units, subdivision of large ones,
/// region clusters and anchors. Afterwards the files are edited by hand; bootstrap never rewrites an existing entry.
/// </summary>
internal static class Bootstrap
{
    /// <summary>Upper bound on regions per modern country: great-power actors must stay within 5-15 regions (#171).</summary>
    private static readonly Dictionary<string, int> RegionCap = new()
    {
        ["RUS"] = 6, ["UKR"] = 3, ["BLR"] = 1, ["MDA"] = 1, ["EST"] = 1, ["LVA"] = 1, ["LTU"] = 1,
    };
    private const double RegionUnitKm2 = 50000;   // k = round(sqrt(area / unit))

    public static string Slug(string name)
    {
        var sb = new StringBuilder();
        foreach (var ch in name.Normalize(NormalizationForm.FormD))
        {
            if (ch is '\'' or '\u2019' or '\u02bc') continue;
            if (CharUnicodeInfo.GetUnicodeCategory(ch) == UnicodeCategory.NonSpacingMark) continue;
            switch (ch)
            {
                case 'ß': sb.Append("ss"); break;
                case 'ø': case 'Ø': sb.Append('o'); break;
                case 'æ': case 'Æ': sb.Append("ae"); break;
                case 'ł': case 'Ł': sb.Append('l'); break;
                case 'đ': case 'Đ': sb.Append("dj"); break;
                case 'þ': case 'Þ': sb.Append("th"); break;
                case 'ð': case 'Ð': sb.Append('d'); break;
                default: sb.Append(char.ToLowerInvariant(ch)); break;
            }
        }
        var s = new StringBuilder();
        foreach (var ch in sb.ToString()) s.Append(ch is >= 'a' and <= 'z' or >= '0' and <= '9' ? ch : '_');
        var t = System.Text.RegularExpressions.Regex.Replace(s.ToString(), "_+", "_").Trim('_');
        if (t.Length == 0 || !char.IsLetter(t[0])) t = "p" + t;
        return t.Length > 36 ? t[..36].TrimEnd('_') : t;
    }

    public static void Run(string specDir, List<Atom> atoms, Func<string, OhmShape> ohm)
    {
        var spec = SpecSet.Load(specDir);
        var min = spec.Area.MinAreaKm2 * 1e6;
        var max = spec.Area.MaxAreaKm2 * 1e6;
        var mergeFile = Path.Combine(specDir, "10-merge-europe.yaml");
        var subFile = Path.Combine(specDir, "15-subdivide-europe.yaml");

        if (!File.Exists(mergeFile)) WriteMerges(mergeFile, atoms, spec, min);
        spec = SpecSet.Load(specDir);

        var pieces = Pipeline.Apply(Pipeline.Initial(atoms), spec, ohm);
        var unanchored = new List<Piece>();
        Ids.Assign(pieces, spec.Ids, unanchored);

        var newIds = new List<IdEntry>();
        var newRegions = new List<RegionEntry>();
        var allIds = new HashSet<string>(spec.Ids.Select(i => i.Id), StringComparer.Ordinal);
        var regionIds = new HashSet<string>(spec.Regions.Select(r => r.Id), StringComparer.Ordinal);

        // Large units without a subdivide rule are subdivided; the cells get ids after their region is known.
        var needSub = unanchored.Where(p => p.SubBase == null && Sph.AreaM2(p.Shape) > max).ToList();
        var units = unanchored.Where(p => p.SubBase == null && !needSub.Contains(p) && p.Cuts.Count == 0).ToList();
        var bigUnits = needSub.Where(p => p.Cuts.Count == 0).ToList();
        var clusterable = units.Concat(bigUnits).ToList();

        var regionOf = Cluster(clusterable, regionIds, newRegions);
        var bases = new Dictionary<Piece, string>();
        foreach (var p in clusterable)
        {
            var region = regionOf[p];
            var id = Unique(region + "." + Slug(p.Name), allIds);
            bases[p] = id;
            if (!bigUnits.Contains(p)) { newIds.Add(Entry(id, p)); }
        }

        if (bigUnits.Count > 0)
        {
            var sb = new StringBuilder("# Generated by 'bootstrap': subdivision of units above max_area_km2 (ADR-0011 §2.3). Edit by hand afterwards.\nrules:\n");
            foreach (var p in bigUnits)
            {
                int parts = (int)Math.Ceiling(Sph.AreaM2(p.Shape) / 1e11);
                sb.Append(FormattableString.Invariant($"  - subdivide: {{within: [{string.Join(", ", p.Src)}], parts: {parts}, base: {bases[p]}, method: voronoi}}\n"));
            }
            File.AppendAllText(subFile, File.Exists(subFile) ? sb.ToString().Split('\n', 3)[2] : sb.ToString());
            spec = SpecSet.Load(specDir);
            pieces = Pipeline.Apply(Pipeline.Initial(atoms), spec, ohm);
            unanchored = new List<Piece>();
            Ids.Assign(pieces, spec.Ids.Concat(newIds).ToList(), unanchored);
        }

        // Cells of subdivided units and halves of cut units.
        foreach (var p in unanchored.ToList())
        {
            string? id = null;
            if (p.SubBase != null)
            {
                var cell = p.SubBase + "_" + p.SubK;
                id = p.Cuts.Count == 0 ? cell : Unique(cell + "_" + Slug(p.Hint), allIds);
            }
            else
            {
                var sib = pieces.FirstOrDefault(q => q.Id != "" && q.Src.Overlaps(p.Src) && !ReferenceEquals(q, p));
                if (sib != null) id = Unique(sib.Id + "_" + Slug(p.Hint), allIds);
            }
            if (id == null) continue;
            allIds.Add(id);
            newIds.Add(Entry(id, p));
            p.Id = id;
        }

        AppendIds(Path.Combine(specDir, "ids", "europe.yaml"), newIds);
        pieces = Pipeline.Apply(Pipeline.Initial(atoms), spec, ohm);
        Ids.Assign(pieces, spec.Ids.Concat(newIds).ToList(), new List<Piece>());
        AppendRegions(Path.Combine(specDir, "regions", "europe.yaml"), newRegions, pieces);
        Console.WriteLine($"bootstrap: {newIds.Count} ids, {newRegions.Count} regions appended");
    }

    private static IdEntry Entry(string id, Piece p)
    {
        var ip = p.Shape.InteriorPoint;
        return new IdEntry { Id = id, Anchor = new[] { Sph.Micro(ip.Y), Sph.Micro(ip.X) } };
    }

    private static string Unique(string id, HashSet<string> used)
    {
        var res = id; int n = 2;
        while (used.Contains(res)) res = id + "_" + n++;
        return res;
    }

    // ---- merges ----

    /// <summary>Greedy merge: the smallest unit below the band joins its smallest same-country neighbour until none is left.</summary>
    private static void WriteMerges(string file, List<Atom> atoms, SpecSet spec, double min)
    {
        var keep = spec.Rules.Where(r => r.Rule.Keep != null).SelectMany(r => r.Rule.Keep!.Codes).ToHashSet(StringComparer.Ordinal);
        var nb = Neighbours(atoms);
        var units = atoms.ToDictionary(a => a.Code, a => new List<string> { a.Code }, StringComparer.Ordinal);
        var unitOf = atoms.ToDictionary(a => a.Code, a => a.Code, StringComparer.Ordinal);
        var area = atoms.ToDictionary(a => a.Code, a => a.AreaM2, StringComparer.Ordinal);
        var adm0 = atoms.ToDictionary(a => a.Code, a => a.Adm0, StringComparer.Ordinal);
        var centroid = atoms.ToDictionary(a => a.Code, a => a.Shape.Centroid.Coordinate, StringComparer.Ordinal);
        while (true)
        {
            string? pick = null;
            foreach (var u in units.Keys.OrderBy(k => area[k]).ThenBy(k => k, StringComparer.Ordinal))
            {
                if (area[u] >= min || units[u].Any(keep.Contains)) continue;
                if (NeighbourUnits(u, units, unitOf, nb, adm0, keep).Count > 0 || NearestSmall(u, units, area, adm0, min, keep, centroid) != "") { pick = u; break; }
            }
            if (pick == null) break;
            var cand = NeighbourUnits(pick, units, unitOf, nb, adm0, keep);
            string target;
            if (cand.Count > 0) target = cand.OrderBy(k => area[k]).ThenBy(k => k, StringComparer.Ordinal).First();
            else
            {
                // Sub-band units of one country that do not touch (island groups such as Aland) join their nearest sub-band sibling.
                target = NearestSmall(pick, units, area, adm0, min, keep, centroid);
            }
            foreach (var c in units[pick]) { units[target].Add(c); unitOf[c] = target; }
            area[target] += area[pick];
            units.Remove(pick); area.Remove(pick);
        }
        var sb = new StringBuilder("# Generated by 'bootstrap': greedy merge of units smaller than min_area_km2 into the smallest same-country neighbour.\n# Edit by hand afterwards; this file is never regenerated.\nrules:\n");
        foreach (var u in units.Keys.OrderBy(k => k, StringComparer.Ordinal))
            if (units[u].Count > 1)
                sb.Append(FormattableString.Invariant($"  - merge: {{from: [{string.Join(", ", units[u].OrderBy(c => c, StringComparer.Ordinal))}]}}\n"));
        File.WriteAllText(file, sb.ToString());
    }

    private static string NearestSmall(string u, Dictionary<string, List<string>> units, Dictionary<string, double> area,
        Dictionary<string, string> adm0, double min, HashSet<string> keep, Dictionary<string, NetTopologySuite.Geometries.Coordinate> centroid)
    {
        double Dist(string a, string b)
        {
            var ca = centroid[a]; var cb = centroid[b];
            return (ca.X - cb.X) * (ca.X - cb.X) + (ca.Y - cb.Y) * (ca.Y - cb.Y);
        }
        return units.Keys.Where(k => k != u && adm0[k] == adm0[u] && area[k] < min && !units[k].Any(keep.Contains))
            .OrderBy(k => Dist(u, k)).ThenBy(k => k, StringComparer.Ordinal).FirstOrDefault() ?? "";
    }

    private static List<string> NeighbourUnits(string u, Dictionary<string, List<string>> units, Dictionary<string, string> unitOf,
        Dictionary<string, SortedSet<string>> nb, Dictionary<string, string> adm0, HashSet<string> keep)
    {
        var res = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var c in units[u])
            foreach (var n in nb[c])
            {
                var nu = unitOf[n];
                if (nu != u && adm0[nu] == adm0[u] && !units[nu].Any(keep.Contains)) res.Add(nu);
            }
        return res.ToList();
    }

    /// <summary>Atoms sharing any border line (touching at a point does not count).</summary>
    private static Dictionary<string, SortedSet<string>> Neighbours(List<Atom> atoms)
    {
        var res = atoms.ToDictionary(a => a.Code, _ => new SortedSet<string>(StringComparer.Ordinal), StringComparer.Ordinal);
        var tree = new NetTopologySuite.Index.Strtree.STRtree<int>();
        for (int i = 0; i < atoms.Count; i++) tree.Insert(atoms[i].Shape.EnvelopeInternal, i);
        tree.Build();
        for (int i = 0; i < atoms.Count; i++)
            foreach (var j in tree.Query(atoms[i].Shape.EnvelopeInternal))
            {
                if (j <= i || !atoms[i].Shape.Intersects(atoms[j].Shape)) continue;
                var shared = Sph.Overlay(atoms[i].Shape.Boundary, atoms[j].Shape.Boundary, SpatialFunction.Intersection);
                if (Length(shared) > 0) { res[atoms[i].Code].Add(atoms[j].Code); res[atoms[j].Code].Add(atoms[i].Code); }
            }
        return res;
    }

    public static double Length(Geometry g)
    {
        double km = 0;
        for (int i = 0; i < g.NumGeometries; i++)
            if (g.GetGeometryN(i) is LineString ls)
            {
                var cs = ls.Coordinates;
                for (int k = 1; k < cs.Length; k++) km += Sph.DistKm(cs[k - 1].X, cs[k - 1].Y, cs[k].X, cs[k].Y);
            }
        return km;
    }

    // ---- regions ----

    /// <summary>Per-country k-means on area-weighted centroids; deterministic farthest-point initialisation.</summary>
    private static Dictionary<Piece, string> Cluster(List<Piece> units, HashSet<string> regionIds, List<RegionEntry> newRegions)
    {
        var res = new Dictionary<Piece, string>();
        foreach (var grp in units.GroupBy(u => u.Adm0).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            var us = grp.OrderBy(u => u.Name, StringComparer.Ordinal).ThenBy(u => u.Src.First(), StringComparer.Ordinal).ToList();
            double total = us.Sum(u => Sph.AreaM2(u.Shape)) / 1e6;
            int k = (int)Math.Round(Math.Sqrt(total / RegionUnitKm2), MidpointRounding.ToEven);
            k = Math.Clamp(k, 1, Math.Min(RegionCap.GetValueOrDefault(grp.Key, 99), us.Count));
            var pts = us.Select(u => { var c = u.Shape.Centroid; return (X: c.X * Math.Cos(c.Y * Math.PI / 180), Y: c.Y); }).ToList();
            var w = us.Select(u => Sph.AreaM2(u.Shape)).ToList();
            var centers = new List<(double X, double Y)> { pts[w.IndexOf(w.Max())] };
            while (centers.Count < k)
            {
                int far = Enumerable.Range(0, us.Count).OrderByDescending(i => centers.Min(c => D2(c, pts[i]))).First();
                centers.Add(pts[far]);
            }
            var assign = new int[us.Count];
            for (int it = 0; it < 20; it++)
            {
                for (int i = 0; i < us.Count; i++)
                    assign[i] = Enumerable.Range(0, k).OrderBy(c => D2(centers[c], pts[i])).First();
                for (int c = 0; c < k; c++)
                {
                    var m = Enumerable.Range(0, us.Count).Where(i => assign[i] == c).ToList();
                    if (m.Count == 0) continue;
                    centers[c] = (m.Sum(i => pts[i].X * w[i]) / m.Sum(i => w[i]), m.Sum(i => pts[i].Y * w[i]) / m.Sum(i => w[i]));
                }
            }
            for (int c = 0; c < k; c++)
            {
                var m = Enumerable.Range(0, us.Count).Where(i => assign[i] == c).ToList();
                if (m.Count == 0) continue;
                var head = m.OrderByDescending(i => w[i]).First();
                var country = Slug(us[head].Admin);
                var rid = Unique(k == 1 ? country : country + "_" + Slug(us[head].Name), regionIds);
                regionIds.Add(rid);
                newRegions.Add(new RegionEntry { Id = rid });
                foreach (var i in m) res[us[i]] = rid;
            }
        }
        return res;
    }

    private static double D2((double X, double Y) a, (double X, double Y) b) => (a.X - b.X) * (a.X - b.X) + (a.Y - b.Y) * (a.Y - b.Y);

    // ---- writers ----

    private static void AppendIds(string file, List<IdEntry> ids)
    {
        if (ids.Count == 0) return;
        Directory.CreateDirectory(Path.GetDirectoryName(file)!);
        var sb = new StringBuilder();
        if (!File.Exists(file)) sb.Append("# Province ids and anchor points [lat_udeg, lon_udeg] (ADR-0011 §1). Written by 'bootstrap'; edited by hand afterwards.\nids:\n");
        foreach (var e in ids.OrderBy(i => i.Id, StringComparer.Ordinal))
            sb.Append(FormattableString.Invariant($"  - {{id: {e.Id}, anchor: [{e.Anchor[0]}, {e.Anchor[1]}]}}\n"));
        File.AppendAllText(file, sb.ToString());
    }

    private static void AppendRegions(string file, List<RegionEntry> regions, List<Piece> pieces)
    {
        if (regions.Count == 0) return;
        Directory.CreateDirectory(Path.GetDirectoryName(file)!);
        var sb = new StringBuilder();
        if (!File.Exists(file)) sb.Append("# Regions (ADR-0011 §1). Province membership is the id prefix. Written by 'bootstrap'; edited by hand afterwards.\nregions:\n");
        foreach (var r in regions.OrderBy(r => r.Id, StringComparer.Ordinal))
        {
            var cap = pieces.Where(p => p.Id.StartsWith(r.Id + ".", StringComparison.Ordinal)).OrderByDescending(p => Sph.AreaM2(p.Shape)).ThenBy(p => p.Id, StringComparer.Ordinal).First();
            sb.Append(FormattableString.Invariant($"  - {{id: {r.Id}, capital: {cap.Id}, isolated: false}}\n"));
        }
        File.AppendAllText(file, sb.ToString());
    }
}
