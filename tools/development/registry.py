#!/usr/bin/env python3
"""Project registry tool for PROJECT SINGULARITY.

Every tracked item (milestone, task, hypothesis, experiment, ADR, research
report) lives in its own Markdown file with YAML frontmatter. This tool:

  check   validate all items (IDs, statuses, required fields, links,
          immutability of ACCEPTED ADRs, freshness of generated files)
  list    print items to the console, optionally filtered
  index   regenerate development/BACKLOG.md and the active-tasks block
          in CURRENT_STATE.md
  new     create a new item from its template with the next free ID

Usage:
  python3 tools/development/registry.py check [--staged | --against REF]
  python3 tools/development/registry.py list [--type TASK] [--status DONE]
  python3 tools/development/registry.py index
  python3 tools/development/registry.py new TASK "Title of the task"
  python3 tools/development/registry.py set-status TASK-0001 DONE

Only dependency outside the standard library: PyYAML.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - environment problem, not a bug
    sys.exit("registry.py needs PyYAML: pip install pyyaml")

ROOT = Path(__file__).resolve().parents[2]

# --------------------------------------------------------------------------
# Item type definitions
# --------------------------------------------------------------------------

APPROVAL_FIELDS = ["approved_by", "approved_at", "approval_ref"]
REPRO_FIELDS = ["core_commit", "data_hash", "manifest_hash", "seeds",
                "threads", "golden_hash", "outcome"]


@dataclass
class ItemType:
    prefix: str            # ID prefix, e.g. "TASK"
    folder: str            # folder relative to ROOT
    id_pattern: str        # regex for the full ID
    statuses: list[str]
    required: list[str]    # always required frontmatter fields
    template: str          # template file name in development/templates
    approval_statuses: list[str] = field(default_factory=list)
    link_fields: list[str] = field(default_factory=list)  # fields holding IDs


TYPES: dict[str, ItemType] = {
    "MS": ItemType(
        "MS", "development/milestones", r"MS-M\d+",
        ["PLANNED", "ACTIVE", "RELEASED"],
        ["id", "title", "status"], "milestone.md",
        approval_statuses=["ACTIVE", "RELEASED"]),
    "TASK": ItemType(
        "TASK", "development/tasks", r"TASK-\d{4}",
        ["PROPOSED", "APPROVED", "IN_PROGRESS", "REVIEW", "DONE",
         "BLOCKED", "REJECTED", "DEFERRED"],
        ["id", "title", "status", "level", "milestone", "agent"], "task.md",
        approval_statuses=["APPROVED", "IN_PROGRESS", "REVIEW", "DONE"],
        link_fields=["milestone", "depends_on", "related"]),
    "HYP": ItemType(
        "HYP", "development/hypotheses", r"HYP-\d{4}",
        ["IDEA", "HYPOTHESIS", "UNDER_RESEARCH", "EXPERIMENTAL",
         "VALIDATED", "REJECTED", "DEFERRED"],
        ["id", "title", "status"], "hypothesis.md",
        approval_statuses=["EXPERIMENTAL", "VALIDATED"],
        link_fields=["related"]),
    "EXP": ItemType(
        "EXP", "development/experiments", r"EXP-\d{4}",
        ["PLANNED", "RUNNING", "DONE", "FAILED"],
        ["id", "title", "status", "hypothesis"], "experiment.md",
        link_fields=["hypothesis", "related"]),
    "ADR": ItemType(
        "ADR", "docs/decisions", r"ADR-\d{4}",
        ["PROPOSED", "ACCEPTED", "SUPERSEDED", "DEPRECATED", "REJECTED"],
        ["id", "title", "status", "date"], "adr.md",
        approval_statuses=["ACCEPTED"],
        link_fields=["superseded_by", "supersedes", "related"]),
    "RR": ItemType(
        "RR", "docs/research", r"RR-\d{4}",
        ["DRAFT", "FINAL", "SUPERSEDED"],
        ["id", "title", "status", "date"], "research-report.md",
        link_fields=["related"]),
}

TASK_LEVELS = ["light", "gate", "gate+research"]
EXP_OUTCOMES = ["supports", "refutes", "inconclusive"]
# Fields of an ACCEPTED ADR that may still change.
ADR_MUTABLE_FIELDS = {"status", "superseded_by"}

BACKLOG = ROOT / "development" / "BACKLOG.md"
CURRENT_STATE = ROOT / "CURRENT_STATE.md"
ACTIVE_START = "<!-- registry:active:start -->"
ACTIVE_END = "<!-- registry:active:end -->"
GENERATED_NOTE = "<!-- GENERATED by tools/development/registry.py index — do not edit -->"

# --------------------------------------------------------------------------
# Parsing
# --------------------------------------------------------------------------

FRONTMATTER_RE = re.compile(r"\A---\n(.*?)\n---\n?(.*)\Z", re.S)


@dataclass
class Item:
    type: ItemType
    path: Path
    meta: dict
    body: str

    @property
    def id(self) -> str:
        return str(self.meta.get("id", ""))


def split_frontmatter(text: str) -> tuple[dict | None, str]:
    """Return (frontmatter dict or None, body)."""
    m = FRONTMATTER_RE.match(text)
    if not m:
        return None, text
    data = yaml.safe_load(m.group(1)) or {}
    if not isinstance(data, dict):
        return None, text
    return data, m.group(2)


def as_list(value) -> list[str]:
    if value is None or value == "":
        return []
    if isinstance(value, list):
        return [str(v) for v in value if v not in (None, "")]
    return [str(value)]


def load_items(errors: list[str]) -> list[Item]:
    items: list[Item] = []
    for t in TYPES.values():
        folder = ROOT / t.folder
        if not folder.is_dir():
            continue
        for path in sorted(folder.glob(f"{t.prefix}-*.md")):
            try:
                meta, body = split_frontmatter(path.read_text(encoding="utf-8"))
            except yaml.YAMLError as exc:
                errors.append(f"{rel(path)}: invalid YAML frontmatter: {exc}")
                continue
            if meta is None:
                errors.append(f"{rel(path)}: missing YAML frontmatter")
                continue
            items.append(Item(t, path, meta, body))
    return items


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


# --------------------------------------------------------------------------
# check
# --------------------------------------------------------------------------

def check_items(items: list[Item], errors: list[str]) -> None:
    ids = {}
    for it in items:
        where = rel(it.path)
        t = it.type
        for f in t.required:
            if it.meta.get(f) in (None, ""):
                errors.append(f"{where}: missing required field '{f}'")
        if not re.fullmatch(t.id_pattern, it.id):
            errors.append(f"{where}: id '{it.id}' does not match {t.id_pattern}")
        elif not it.path.name.startswith(it.id):
            errors.append(f"{where}: file name must start with id '{it.id}'")
        if it.id in ids:
            errors.append(f"{where}: duplicate id '{it.id}' (also {ids[it.id]})")
        ids[it.id] = where

        status = it.meta.get("status")
        if status not in t.statuses:
            errors.append(f"{where}: status '{status}' not in {t.statuses}")
        if status in t.approval_statuses:
            for f in APPROVAL_FIELDS:
                if it.meta.get(f) in (None, ""):
                    errors.append(f"{where}: status {status} needs '{f}'")
            by = it.meta.get("approved_by")
            if by not in (None, "", "owner", "orchestrator"):
                errors.append(f"{where}: approved_by must be owner|orchestrator")
            if by == "orchestrator" and t.prefix == "TASK" \
                    and it.meta.get("level") != "light":
                errors.append(f"{where}: only light tasks may be approved by orchestrator")
            if by == "orchestrator" and t.prefix in ("ADR", "MS", "HYP"):
                errors.append(f"{where}: {t.prefix} must be approved by owner")

        if t.prefix == "TASK" and it.meta.get("level") not in TASK_LEVELS:
            errors.append(f"{where}: level must be one of {TASK_LEVELS}")
        if t.prefix == "EXP" and status == "DONE":
            for f in REPRO_FIELDS:
                if it.meta.get(f) in (None, ""):
                    errors.append(f"{where}: DONE experiment needs '{f}'")
            if it.meta.get("outcome") not in EXP_OUTCOMES:
                errors.append(f"{where}: outcome must be one of {EXP_OUTCOMES}")
        if t.prefix == "ADR" and status == "SUPERSEDED" \
                and not it.meta.get("superseded_by"):
            errors.append(f"{where}: SUPERSEDED ADR needs 'superseded_by'")

    for it in items:
        for f in it.type.link_fields:
            for ref in as_list(it.meta.get(f)):
                if ref not in ids:
                    errors.append(f"{rel(it.path)}: field '{f}' points to unknown id '{ref}'")


def git(*args: str) -> str | None:
    try:
        out = subprocess.run(["git", *args], cwd=ROOT, capture_output=True,
                             text=True, check=True)
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None
    return out.stdout


def check_accepted_adrs(items: list[Item], errors: list[str],
                        staged: bool, against: str | None) -> None:
    """An ADR that was ACCEPTED in the base version may change only its
    status / superseded_by fields. Base = HEAD (staged mode) or REF."""
    if not staged and not against:
        return
    base = "HEAD" if staged else against
    for it in items:
        if it.type.prefix != "ADR":
            continue
        path = rel(it.path)
        old_text = git("show", f"{base}:{path}")
        if old_text is None:
            continue  # new file
        new_text = git("show", f":{path}") if staged else it.path.read_text(encoding="utf-8")
        if new_text is None:
            continue
        old_meta, old_body = split_frontmatter(old_text)
        new_meta, new_body = split_frontmatter(new_text)
        if not old_meta or old_meta.get("status") != "ACCEPTED":
            continue
        new_meta = new_meta or {}
        changed = {k for k in set(old_meta) | set(new_meta)
                   if old_meta.get(k) != new_meta.get(k)} - ADR_MUTABLE_FIELDS
        if changed or old_body.strip() != new_body.strip():
            what = ", ".join(sorted(changed)) or "body"
            errors.append(f"{path}: ACCEPTED ADR changed ({what}). "
                          "Write a new ADR that supersedes it.")


def check_generated(items: list[Item], errors: list[str]) -> None:
    if BACKLOG.exists() and BACKLOG.read_text(encoding="utf-8") != render_backlog(items):
        errors.append("development/BACKLOG.md is stale: run registry.py index")
    if CURRENT_STATE.exists():
        text = CURRENT_STATE.read_text(encoding="utf-8")
        if ACTIVE_START in text and replace_active_block(text, items) != text:
            errors.append("CURRENT_STATE.md active block is stale: run registry.py index")


def cmd_check(args) -> int:
    errors: list[str] = []
    items = load_items(errors)
    check_items(items, errors)
    check_accepted_adrs(items, errors, args.staged, args.against)
    check_generated(items, errors)
    if errors:
        print("registry check FAILED:")
        for e in errors:
            print("  -", e)
        return 1
    print(f"registry check OK ({len(items)} items)")
    return 0


