using System.Security.Cryptography;
using System.Text;

namespace Singularity.MapBuilder;

/// <summary>Writes the core tables (hashed) and geo/ (not hashed): provinces, regions, adjacency, straits, arcs.bin, manifest.json (ADR-0011 §2.11, §4, §5).</summary>
internal static class Writer
{
    private static readonly UTF8Encoding Utf8 = new(false);

    public static void Write(BuildResult r, string outDir)
    {
        Directory.CreateDirectory(Path.Combine(outDir, "geo"));
        var prov = Provinces(r);
        var adj = Adjacency(r);
        var reg = Regions(r);
        var strait = Straits(r);
        File.WriteAllBytes(Path.Combine(outDir, "territories.yaml"), Territories(r));
        File.WriteAllBytes(Path.Combine(outDir, "provinces.yaml"), prov);
        File.WriteAllBytes(Path.Combine(outDir, "adjacency.yaml"), adj);
        File.WriteAllBytes(Path.Combine(outDir, "regions.yaml"), reg);
        File.WriteAllBytes(Path.Combine(outDir, "straits.yaml"), strait);
        File.WriteAllBytes(Path.Combine(outDir, "ATTRIBUTION.md"), Attribution(r));

        var binding = SHA256.HashData(prov.Concat(adj).Concat(reg).ToArray());
        var arcs = ArcsBin(r.Simple, binding);
        File.WriteAllBytes(Path.Combine(outDir, "geo", "arcs.bin"), arcs);
        File.WriteAllBytes(Path.Combine(outDir, "geo", "manifest.json"), Manifest(r, binding, arcs));
    }

    private static byte[] Text(string s) => Utf8.GetBytes(s.Replace("\r\n", "\n"));

    private static string Pt(int lat, int lon) => FormattableString.Invariant($"[{lat}, {lon}]");

    public static byte[] Provinces(BuildResult r)
    {
        var sb = new StringBuilder("# Generated by tools/map (ADR-0011 §2.11). Do not edit: rebuild with 'MapBuilder build'.\n# centroid, label: [lat_udeg, lon_udeg]. Area: km2 on the authalic sphere.\nprovinces:\n");
        for (int i = 0; i < r.Pieces.Count; i++)
        {
            var p = r.Pieces[i];
            var c = p.Shape.Centroid; var ip = p.Shape.InteriorPoint;
            sb.Append(FormattableString.Invariant($"  - {{id: {p.Id}, area_km2: {p.AreaKm2}, centroid: {Pt(Sph.Micro(c.Y), Sph.Micro(c.X))}, label: {Pt(Sph.Micro(ip.Y), Sph.Micro(ip.X))}, coastal: {(r.Coastal[i] ? "true" : "false")}}}\n"));
        }
        return Text(sb.ToString());
    }

    public static byte[] Adjacency(BuildResult r)
    {
        var sb = new StringBuilder("# Generated by tools/map. Pairs of provinces with a shared border of at least 1 km, sorted.\nadjacency:\n");
        foreach (var (a, b) in r.Adjacency.Keys) sb.Append(FormattableString.Invariant($"  - [{a}, {b}]\n"));
        return Text(sb.ToString());
    }

    public static byte[] Regions(BuildResult r)
    {
        var sb = new StringBuilder("# Generated by tools/map from spec/regions.\nregions:\n");
        foreach (var g in r.Spec.Regions.OrderBy(x => x.Id, StringComparer.Ordinal))
            sb.Append(FormattableString.Invariant($"  - {{id: {g.Id}, capital_province: {g.Capital}, isolated: {(g.Isolated ? "true" : "false")}}}\n"));
        return Text(sb.ToString());
    }

    /// <summary>Territories without geometry (ADR-0020 §1.4): rows of the province table that follow the provinces with geometry, in id order.</summary>
    public static byte[] Territories(BuildResult r)
    {
        var sb = new StringBuilder("# Generated by tools/map from spec/territories.yaml. Small territories with ownership but no geometry (ADR-0020 §1.4).\nterritories:\n");
        foreach (var t in r.Spec.Territories.OrderBy(x => x.Id, StringComparer.Ordinal))
            sb.Append(FormattableString.Invariant($"  - {{id: {t.Id}, region: {t.Id[..t.Id.IndexOf('.')]}}}\n"));
        return Text(sb.ToString());
    }

    public static byte[] Straits(BuildResult r)
    {
        var sb = new StringBuilder("# Generated by tools/map from spec/straits.yaml. Manual connections across water.\nstraits:\n");
        foreach (var (a, b) in r.Straits) sb.Append(FormattableString.Invariant($"  - [{a}, {b}]\n"));
        return Text(sb.ToString());
    }

    /// <summary>Little-endian arcs.bin: header, arcs (delta-coded int32 micro-degrees), province rings of signed arc refs (arc index + 1).</summary>
    public static byte[] ArcsBin(Topology t, byte[] binding)
    {
        using var ms = new MemoryStream();
        using var w = new BinaryWriter(ms);
        w.Write(Encoding.ASCII.GetBytes("SGMP"));
        w.Write((uint)1);
        w.Write(binding);
        w.Write((uint)t.Arcs.Count);
        w.Write((uint)t.Rings.Count);
        w.Write((uint)t.Rings.Sum(x => x.Count));
        foreach (var a in t.Arcs)
        {
            w.Write(a.Left); w.Write(a.Right); w.Write((uint)a.V.Count);
            w.Write(a.V[0].Lat); w.Write(a.V[0].Lon);
            for (int i = 1; i < a.V.Count; i++) { w.Write(a.V[i].Lat - a.V[i - 1].Lat); w.Write(a.V[i].Lon - a.V[i - 1].Lon); }
        }
        foreach (var rings in t.Rings)
        {
            w.Write((uint)rings.Count);
            foreach (var ring in rings) { w.Write((uint)ring.Count); foreach (var x in ring) w.Write(x); }
        }
        w.Flush();
        return ms.ToArray();
    }

    /// <summary>
    /// Binding check (ADR-0011 §4): manifest.json must match the canonical bytes of provinces, adjacency and regions, and arcs.bin
    /// (when present) must carry the same binding and the SHA-256 listed in the manifest. A mismatch is a loud error.
    /// </summary>
    public static void VerifyBinding(string mapDir)
    {
        var manifest = System.Text.Json.JsonDocument.Parse(File.ReadAllBytes(Path.Combine(mapDir, "geo", "manifest.json"))).RootElement;
        var bytes = new[] { "provinces.yaml", "adjacency.yaml", "regions.yaml" }.SelectMany(f => File.ReadAllBytes(Path.Combine(mapDir, f))).ToArray();
        var binding = Convert.ToHexString(SHA256.HashData(bytes)).ToLowerInvariant();
        if (manifest.GetProperty("data_binding").GetString() != binding)
            throw new InvalidDataException("geo/manifest.json does not match provinces.yaml, adjacency.yaml and regions.yaml: rebuild geo/ with 'MapBuilder build'");
        var arcsPath = Path.Combine(mapDir, "geo", "arcs.bin");
        if (!File.Exists(arcsPath)) return;
        var arcs = File.ReadAllBytes(arcsPath);
        if (Sources.Sha(arcs) != manifest.GetProperty("files").GetProperty("arcs.bin").GetProperty("sha256").GetString())
            throw new InvalidDataException("geo/arcs.bin differs from the SHA-256 in geo/manifest.json");
        if (Convert.ToHexString(arcs.AsSpan(8, 32)).ToLowerInvariant() != binding)
            throw new InvalidDataException("geo/arcs.bin was built from other tables (data_binding differs)");
    }

    /// <summary>ATTRIBUTION.md: every CC BY object of the OHM snapshots used by cuts (ADR-0011 §2.1). CC0 and public-domain data need no entry.</summary>
    public static byte[] Attribution(BuildResult r)
    {
        var sb = new StringBuilder("# Attribution for the map data\n\nNatural Earth data is public domain. OpenHistoricalMap objects without a licence tag are CC0.\n\n## CC BY objects\n\n");
        var lines = new List<string>();
        foreach (var kv in r.Ohm.OrderBy(kv => kv.Key, StringComparer.Ordinal))
            foreach (var g in kv.Value.Attributions.Select(a => a.Split('|')).GroupBy(p => (Lic: p[0], Credit: p[1])).OrderBy(g => g.Key.Lic, StringComparer.Ordinal).ThenBy(g => g.Key.Credit, StringComparer.Ordinal))
                lines.Add($"- {g.Key.Credit}, {g.Key.Lic}: {string.Join(", ", g.Select(p => p[2]))}; snapshot {kv.Key}, https://www.openhistoricalmap.org");
        sb.Append(lines.Count == 0 ? "None.\n" : string.Join("\n", lines) + "\n");
        return Text(sb.ToString());
    }

    private static string J(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    /// <summary>manifest.json: the only geo/ file kept in git. Provenance is informational and not hashed (ADR-0011 §2.11).</summary>
    public static byte[] Manifest(BuildResult r, byte[] binding, byte[] arcs)
    {
        var sb = new StringBuilder("{\n");
        sb.Append("  \"format_version\": 1,\n");
        sb.Append(FormattableString.Invariant($"  \"data_binding\": {J(Convert.ToHexString(binding).ToLowerInvariant())},\n"));
        sb.Append(FormattableString.Invariant($"  \"files\": {{\"arcs.bin\": {{\"sha256\": {J(Sources.Sha(arcs))}, \"bytes\": {arcs.Length}}}}},\n"));
        sb.Append(FormattableString.Invariant($"  \"counts\": {{\"provinces\": {r.Pieces.Count}, \"territories\": {r.Spec.Territories.Count}, \"regions\": {r.Spec.Regions.Count}, \"arcs\": {r.Simple.Arcs.Count}}},\n"));
        sb.Append("  \"sources\": [\n");
        sb.Append(string.Join(",\n", r.Lock.Sources.Select(s => $"    {{\"id\": {J(s.Id)}, \"sha256\": {J(s.Sha256)}, \"license\": {J(s.License)}}}")));
        sb.Append("\n  ],\n  \"provenance\": {\n");
        sb.Append(string.Join(",\n", r.Pieces.Select(p =>
            $"    {J(p.Id)}: {{\"ne_src\": [{string.Join(", ", p.Src.Select(J))}], \"cuts\": [{string.Join(", ", p.Cuts.Select(J))}]}}")));
        sb.Append("\n  }\n}\n");
        return Text(sb.ToString());
    }
}
