TWO53 = 1 << 53


def prob_threshold(p_raw):
    """ADR-0003 R2: floor(p_raw * 2^53 / 10^6), Int128."""
    return (p_raw * TWO53) // SCALE


def prob_check(u, p_raw):
    r = u >> 11
    thr = prob_threshold(p_raw)
    return {"u": u, "r": r, "threshold": thr, "hit": r < thr}


def draw_profile(u):
    return ((u >> 11) * 3) >> 53                         # spec 9.2: floor(3U)


def draw_j(u):
    return 500_000 + (((u >> 11) * 1_000_001) >> 53)     # spec 9.2: j in [0.5; 1.5] Fx6


def draw_uniform_int(u, lo, hi):
    return lo + (((u >> 11) * (hi - lo + 1)) >> 53)      # spec 9.2


# ---------------------------------------------------------------- contract v2.3 4.1 (R0): culture_H step — ABLATION since v2.4
# Kept bit-exact as the ablation "C-B -> R0 v2.3" (contract v2.4 4.1 "Заменяемость", spec v0.11 6.2) and for
# the existing D1/D4 tests (formulas.json "culture_H", trajectory.json). The main rule is culture_step_cb below.
def culture_step(i):
    """R0 v2.3 (ablation). One cell culture_H[site,c,d]. Input dict (all Fx6 raw unless noted):
    H, Hcap, phi_floor, alpha, k_qp, qp_active(bool), d_is_qc(bool), act, act_norm, w,
    k_catch, sigma, rho_max, delta_H,
    procs: [{prc_id, v, r_d, world_lead(bool)}]  (v = 0 or the process is absent when yield_p = 0),
    spill_in: [{cluster, R, H_other}]  (same d, other clusters c' of the site, snapshot values).
    """
    H = i["H"]
    procs = sorted(i["procs"], key=lambda p: p["prc_id"])
    V = add(*[p["v"] for p in procs]) if procs else 0
    out = {"V_c": V, "s_p": []}
    drive = catch = maint = ZERO
    if V != 0:
        act_ratio = min(ONE, div(i["act"], i["act_norm"]))
        for p in procs:
            s = div(p["v"], V)
            above = max(ZERO, add(p["r_d"], fx("0.25"), -H))
            drive = add(drive, mul(s, above))
            if p["world_lead"]:
                catch = add(catch, mul(s, above))   # world_lead in {0,1}: multiply == select
            maint = add(maint, mul(mul(s, p["r_d"]), act_ratio))
            out["s_p"].append({"prc_id": p["prc_id"], "s": s})
    spill = ZERO
    for sp in sorted(i["spill_in"], key=lambda x: x["cluster"]):
        spill = add(spill, mul(sp["R"], max(ZERO, sp["H_other"] - H)))
    H_floor = mul(i["phi_floor"], i["Hcap"])
    sat = max(ZERO, ONE - div(H, i["Hcap"]))
    alpha_eff = mul(i["alpha"], ONE + i["k_qp"]) if (i["qp_active"] and i["d_is_qc"]) else i["alpha"]
    inner = add(mul(mul(mul(alpha_eff, i["act"]), i["w"]), drive),
                mul(i["k_catch"], catch),
                mul(i["sigma"], spill))
    dH_plus = mul(sat, inner)
    dH_minus = mul(i["delta_H"], max(ZERO, H - max(maint, H_floor)))
    H_new = add(H, min(dH_plus, i["rho_max"]), -dH_minus)
    out.update({"drive": drive, "catch": catch, "maint": maint, "spill": spill, "H_floor": H_floor,
                "sat": sat, "alpha_eff": alpha_eff, "dH_plus": dH_plus,
                "dH_plus_capped": min(dH_plus, i["rho_max"]), "dH_minus": dH_minus, "H_new": H_new})
    return out


# ---------------------------------------------------------------- contract 4.2: yield and production_profile
DIMS = ["precision", "purity", "quality_control"]        # fixed order = product order (A1)


def g_gap(gap):
    if gap < fi(-1):
        return ZERO
    if gap < ZERO:
        t = ONE + gap
        return mul(t, t)
    return ONE


def ramp(X, Xh, lam0):
    return add(lam0, div(mul(ONE - lam0, X), add(X, Xh)))   # spec 3.2, left to right


def yield_p(p):
    """p: {prc_id, req{dim: Fx6|None}, H{dim}, M{dim}, X, Xh, lam0, l_lic(Fx6|None)}."""
    dims = []
    acc = ONE
    for d in DIMS:
        r = p["req"].get(d)
        if r is None or r <= 0:
            continue
        c = min(p["H"][d], p["M"][d])
        src = "H" if p["H"][d] <= p["M"][d] else "M"      # tie H = M -> H (spec 3.5 A5)
        g = g_gap(c - r)
        acc = mul(acc, g)
        dims.append({"dim": d, "c_d": c, "src": src, "gap": c - r, "g": g})
    Xh = p["Xh"] if p.get("l_lic") is None else mul(p["Xh"], ONE - p["l_lic"])
    rp = ramp(p["X"], Xh, p["lam0"])
    # contract 4.2 A4: q_p = g(c_qc - r_qc) if r_qc > 0, else 1
    q_p = next((d["g"] for d in dims if d["dim"] == "quality_control"), ONE)
    return {"prc_id": p["prc_id"], "dims": dims, "Xh_eff": Xh, "ramp": rp, "yield": mul(acc, rp), "q_p": q_p}


def production_profile(case):
    """case: {procs: [yield_p input + n_p (Fx6), base_cost (Fx6), known(bool)], eps}."""
    rows = [dict(yield_p(p), n_p=p["n_p"], base_cost=p["base_cost"], known=p["known"])
            for p in sorted(case["procs"], key=lambda p: p["prc_id"])]
    eps = case["eps"]
    admitted = all(r["yield"] > 0 and r["known"] for r in rows)
    num = den = ZERO
    for r in rows:
        r["yc"] = max(r["yield"], eps)
        nb = mul(r["n_p"], r["base_cost"])
        num = add(num, div(nb, r["yc"]))
        den = add(den, nb)
    ucm = div(num, den)
    bn = min(rows, key=lambda r: (r["yield"], r["prc_id"]))
    if bn["dims"] and min(d["g"] for d in bn["dims"]) < ONE:
        bd = min(bn["dims"], key=lambda d: (d["g"], DIMS.index(d["dim"])))
        bottleneck = {"prc": bn["prc_id"], "dim": bd["dim"], "src": bd["src"]}
    else:
        bottleneck = {"prc": bn["prc_id"], "dim": None, "src": "ramp"}   # spec 3.5 A5
    return {"per_process": rows, "admitted": admitted, "unit_cost_mult": ucm,
            "bottleneck": bottleneck, "q": min(r["q_p"] for r in rows)}   # contract 4.2 A4


# ---------------------------------------------------------------- Kernel helpers v2.4 (contract 4.0 p.2, G4-3, G4-4)
def smoothstep01(x):
    """DetMath.SmoothStep01: floor(X^2*(3S - 2X)/S^2) raw, X = x.Raw, S = 10^6, one rounding (Int128).
    Domain 0 <= x <= 1, otherwise an error (contract 4.0 p.2)."""
    if not ZERO <= x <= ONE:
        raise ValueError("SmoothStep01 domain: %d" % x)
    return _chk((x * x * (3 * SCALE - 2 * x)) // (SCALE * SCALE))


def mul_ceil(a, b):
    """Fx6 MulCeil: ceil(a.Raw*b.Raw/S) raw, a, b >= 0 (contract 4.0 p.2, G4-4)."""
    if a < 0 or b < 0:
        raise ValueError("MulCeil needs a, b >= 0")
    return _chk(-((-(a * b)) // SCALE))


# ---------------------------------------------------------------- contract v2.4 4.1: culture rule C-B (main, RISK-0016)
CB_PARAMS = dict(          # contract v2.4 4.1 table; spec v0.11 8.1 (A37)
    r_cap="10",            # r_ref/2.5, units of process per month
    r_keep="6.25",         # r_ref/4
    k_tr="1",
    E_full_raw=1838,       # manifest raw literal (0.4*0.25*0.239)/13, not recomputed at run time (G4-4)
    ell="0.1", dL="0.5")


def cb_prm(**kw):
    p = {k: (v if isinstance(v, int) and k == "E_full_raw" else fx(v)) for k, v in CB_PARAMS.items()}
    p["E_full"] = p.pop("E_full_raw")
    p.update(kw)
    return p


def cb_terms(v, E, lic, labour, r_d, H, prm):
    """Per-process terms of one cell (contract v2.4 4.1, canonical order 4.0)."""
    l = ONE if lic else ZERO
    v_cap = mul(prm["r_cap"], labour)
    v_keep = mul(prm["r_keep"], labour)
    vt = mul(ONE + mul(prm["k_tr"], l), v)                       # v~ = (1 + k_tr*lic)*v, exact for lic in {0,1}
    x_V = ZERO if v_cap == 0 else min(ONE, div(vt, v_cap))
    c = smoothstep01(x_V)
    x_E = ZERO if prm["E_full"] == 0 else min(ONE, div(E, prm["E_full"]))
    e_V = min(x_E, c)
    e_L = ZERO if prm["ell"] == 0 else min(x_E, prm["ell"])
    gap = max(ZERO, add(r_d, fx("0.25"), -H))
    gapL = max(ZERO, (r_d - prm["dL"]) - H)
    return {"v_cap": v_cap, "v_keep": v_keep, "v_tilde": vt, "x_V": x_V, "c": c, "x_E": x_E, "e_V": e_V,
            "e_L": e_L, "gap": gap, "gapL": gapL, "t": max(mul(e_V, gap), mul(e_L, gapL))}


def culture_step_cb(i):
    """C-B, one cell culture_H[site,c,d] (contract v2.4 4.1). Input = R0 input (culture_base) plus
    cb (params, cb_prm) and procs [{prc_id, v, E, r_d, labour, lic, world_lead}] of the cluster c."""
    H, prm = i["H"], i["cb"]
    H_floor = mul(i["phi_floor"], i["Hcap"])
    a_r = min(ONE, div(i["act"], i["act_norm"]))
    drive = catch = ZERO
    maint = H_floor                                              # empty P(c,d) -> H_floor
    rows = []
    for p in sorted(i["procs"], key=lambda q: q["prc_id"]):
        if p["r_d"] <= 0 or (p["v"] <= 0 and p["E"] <= 0):      # P(c,d): active d and (v > 0 or E > 0)
            continue
        r = cb_terms(p["v"], p["E"], p["lic"], p["labour"], p["r_d"], H, prm)
        m = ZERO if r["v_keep"] == 0 else min(ONE, div(r["v_tilde"], r["v_keep"]))
        maint_p = add(H_floor, mul(max(mul(p["r_d"], a_r), H_floor) - H_floor, m))
        drive = max(drive, r["t"])
        if p["world_lead"]:
            catch = max(catch, r["t"])
        maint = max(maint, maint_p)
        rows.append(dict(r, prc_id=p["prc_id"], m=m, maint_p=maint_p))
    spill = ZERO
    for sp in sorted(i["spill_in"], key=lambda x: x["cluster"]):
        spill = add(spill, mul(sp["R"], max(ZERO, sp["H_other"] - H)))
    sat = max(ZERO, ONE - div(H, i["Hcap"]))
    alpha_eff = mul(i["alpha"], ONE + i["k_qp"]) if (i["qp_active"] and i["d_is_qc"]) else i["alpha"]
    inner = add(mul(mul(mul(alpha_eff, i["act"]), i["w"]), drive), mul(i["k_catch"], catch), mul(i["sigma"], spill))
    dH_plus = mul(sat, inner)
    dH_minus = mul(i["delta_H"], max(ZERO, H - max(maint, H_floor)))
    return {"per_process": rows, "a_r": a_r, "drive": drive, "catch": catch, "maint": maint, "spill": spill,
            "H_floor": H_floor, "sat": sat, "alpha_eff": alpha_eff, "dH_plus": dH_plus,
            "dH_plus_capped": min(dH_plus, i["rho_max"]), "dH_minus": dH_minus,
            "H_new": add(H, min(dH_plus, i["rho_max"]), -dH_minus)}


# ---------------------------------------------------------------- contract v2.4 4.1a: functions of the rule (snapshot)
# site = {H: {(c,d)}, M: {(c,d)}, Hcap: {d}, cb: prm, procs: [{prc_id, cluster, req{d}, v, E, labour, known,
#         planned, lic}]}; lead, limiter0, d*, t_hat are internal; E_useful, limiter, dH_forecast are external.
def active_dims(p):
    return [d for d in DIMS if (p["req"].get(d) or 0) > 0]


def _proc(site, prc):
    return next(p for p in site["procs"] if p["prc_id"] == prc)


def t_hat(site, p, d):
    r = cb_terms(p["v"], ZERO, p["lic"], p["labour"], p["req"][d], site["H"][(p["cluster"], d)], site["cb"])
    return max(mul(r["c"], r["gap"]), mul(site["cb"]["ell"], r["gapL"]))        # v = 0 -> c = 0


def eligible(site, p):
    return p["known"] and (p["v"] > 0 or p["planned"])           # G4-2


def _steps_1_4(site, p, d):
    H, M, prm = site["H"][(p["cluster"], d)], site["M"][(p["cluster"], d)], site["cb"]
    r_d = p["req"][d]
    if max(ZERO, add(r_d, fx("0.25"), -H)) == 0:
        return "NONE"
    if M < H:
        return "TOOLING"
    if site["Hcap"][d] <= r_d:
        return "SATURATION"
    if p["v"] == 0 and (prm["ell"] == 0 or H >= r_d - prm["dL"]):
        return "LAB_CEILING"
    return None


def limiter0_d(site, p, d):
    s = _steps_1_4(site, p, d)
    return s if s else ("EFFORT" if t_hat(site, p, d) > 0 else "VOLUME")   # VOLUME branch is defensive (L4)


def lead(site, c, d):
    cand = [p for p in site["procs"] if p["cluster"] == c and d in active_dims(p) and eligible(site, p)
            and limiter0_d(site, p, d) == "EFFORT"]
    if not cand:
        return None
    return max(cand, key=lambda p: (t_hat(site, p, d), -p["prc_id"]))["prc_id"]


def d_star(site, p):
    led = [d for d in active_dims(p) if lead(site, p["cluster"], d) == p["prc_id"]]
    pool = led or active_dims(p)
    return max(pool, key=lambda d: (p["req"][d] - site["H"][(p["cluster"], d)], -DIMS.index(d)))


def k_star(site, p, d):
    r = cb_terms(p["v"], ZERO, p["lic"], p["labour"], p["req"][d], site["H"][(p["cluster"], d)], site["cb"])
    return site["cb"]["ell"] if mul(site["cb"]["ell"], r["gapL"]) > mul(r["c"], r["gap"]) else r["c"]


def e_useful(site, p):
    d = d_star(site, p)
    if lead(site, p["cluster"], d) != p["prc_id"] or limiter0_d(site, p, d) != "EFFORT":
        return ZERO
    return mul_ceil(k_star(site, p, d), site["cb"]["E_full"])


def _limiter_own(site, p):
    d = d_star(site, p)
    s = _steps_1_4(site, p, d)
    if s:
        return s
    if p["v"] > 0 and p["E"] >= e_useful(site, p) and k_star(site, p, d) < ONE:
        return "VOLUME"
    return "EFFORT"


def limiter(site, p):
    """Contract v2.4 4.1a: (value, subject_prc)."""
    d = d_star(site, p)
    leads_any = any(lead(site, p["cluster"], dd) == p["prc_id"] for dd in active_dims(p))
    if leads_any:
        return _limiter_own(site, p), p["prc_id"]
    q = lead(site, p["cluster"], d)
    if q is not None:
        return _limiter_own(site, _proc(site, q)), q
    if not eligible(site, p) and p["v"] == 0:
        return "LAB_CEILING", p["prc_id"]
    return limiter0_d(site, p, d), p["prc_id"]


def interface_view(site):
    cells = {"%s.%s" % (c, d): lead(site, c, d) for c in sorted({p["cluster"] for p in site["procs"]}) for d in DIMS}
    procs = []
    for p in sorted(site["procs"], key=lambda q: q["prc_id"]):
        if not active_dims(p):
            continue
        d = d_star(site, p)
        lim, subj = limiter(site, p)
        procs.append({"prc_id": p["prc_id"], "eligible": eligible(site, p), "d_star": d,
                      "t_hat": {dd: t_hat(site, p, dd) for dd in active_dims(p)},
                      "limiter0": {dd: limiter0_d(site, p, dd) for dd in active_dims(p)},
                      "k_star": k_star(site, p, d), "E_useful": e_useful(site, p),
                      "limiter": lim, "subject_prc": subj})
    return {"lead": cells, "procs": procs}


def dh_forecast(cell_input, prc, E, v):
    """Contract v2.4 4.1a: min(dH+, rho_max) of the cell with E and v of process prc substituted (UI only)."""
    i = dict(cell_input, procs=[dict(p, E=E, v=v) if p["prc_id"] == prc else p for p in cell_input["procs"]])
    return culture_step_cb(i)["dH_plus_capped"]


# ---------------------------------------------------------------- contract v2.4 4.1b: production engineering split
def gap_H(site, p):
    return max([max(ZERO, p["req"][d] - site["H"][(p["cluster"], d)]) for d in active_dims(p)] + [ZERO])


def effort_allocation(site, D_a, focus, v_exp, r_ref):
    """One actor, one site (slice A27). v_exp {prc: Fx6}. Returns E per known process, rest_a and the trace."""
    known = [p for p in sorted(site["procs"], key=lambda q: q["prc_id"]) if p["known"]]
    Eu = {p["prc_id"]: e_useful(site, p) for p in known}
    E = {p["prc_id"]: ZERO for p in known}
    D_left = D_a
    assert len(set(focus)) == len(focus) and len(focus) <= 3, "focus validator: no repeats, at most 3"
    for q in focus:                                                  # step 0, player only
        E[q] = min(D_left, Eu.get(q, ZERO))
        D_left -= E[q]
    K = [p for p in known if Eu[p["prc_id"]] > 0 and E[p["prc_id"]] < Eu[p["prc_id"]]]   # step 1
    w = {p["prc_id"]: mul(div(v_exp.get(p["prc_id"], ZERO), mul(r_ref, p["labour"])), gap_H(site, p))
         for p in K}                                                 # step 2, normalised (R2-10)
    passes, n_cand = [], len(K)
    while D_left > 0 and K:                                          # step 3, passes (G4-6)
        D0 = D_left
        W = add(*[w[p["prc_id"]] for p in K])
        if W == 0:
            break
        alloc = {p["prc_id"]: div(mul(D0, w[p["prc_id"]]), W) for p in K}
        give = {}
        for p in K:
            k = p["prc_id"]
            give[k] = min(alloc[k], Eu[k] - E[k])
            E[k] += give[k]
            D_left -= give[k]
        full = [p["prc_id"] for p in K if E[p["prc_id"]] == Eu[p["prc_id"]]]
        passes.append({"D0": D0, "W": W, "alloc": alloc, "give": give, "saturated": full})
        K = [p for p in K if E[p["prc_id"]] < Eu[p["prc_id"]]]
        if not full:
            break
    assert len(passes) <= max(1, n_cand)
    assert add(*E.values(), D_left) == D_a if E else D_left == D_a
    assert all(ZERO <= E[k] <= Eu[k] for k in E)
    return {"D_a": D_a, "focus": list(focus), "E_useful": Eu, "w": w, "passes": passes, "E": E, "rest_a": D_left}


def split_by_site(E_ap, sites):
    """Contract v2.4 4.1a: sites [(site_id, v_sp, E_useful_sp)]. share by v (floor), floor remainder to the
    site with max v (tie smaller id); sum v = 0 -> all to the smallest id; E_sp = min(share, E_useful); surplus -> rest_a."""
    sites = sorted(sites)
    tot = add(*[s[1] for s in sites])
    if tot == 0:
        share = {s[0]: (E_ap if s[0] == sites[0][0] else ZERO) for s in sites}
    else:
        share = {s[0]: div(mul(E_ap, s[1]), tot) for s in sites}
        top = max(sites, key=lambda s: (s[1], -s[0]))[0]
        share[top] += E_ap - add(*share.values())
    E = {s[0]: min(share[s[0]], s[2]) for s in sites}
    surplus = add(*[share[k] - E[k] for k in E])
    assert add(*E.values(), surplus) == E_ap
    return {"share": share, "E": E, "surplus": surplus}


