def build():
    for v in RNG_VECTORS:
        assert next_u64(*v[:5]) == v[5], "CounterRng port mismatch"
    import datetime
    base = datetime.date(*START_DATE)
    for d in range(0, 12000, 7):
        assert iso(d) == (base + datetime.timedelta(days=d)).isoformat(), "calendar mismatch"
    assert day_tick(360) == 10957 and day_tick(384) == 11688, "horizon in days"
    assert all(month_fired_at(day_tick(m)) == m for m in range(385))
    assert sum(month_fired_at(d) is not None for d in range(day_tick(384))) == 384
    setup, rows = run_trajectory(TRAJ_SEED)
    cov = coverage(rows)
    traj = {"schema": "jet_slice_reference_trajectory/1", "fx6_scale": SCALE, "seed": TRAJ_SEED,
            "params": TP | {"Xh": {str(k): v for k, v in TP["Xh"].items()}, "X0": {str(k): v for k, v in TP["X0"].items()}},
            "nodes": {str(k): {kk: vv for kk, vv in v.items()} for k, v in NODES.items()},
            "known_at_start": KNOWN_AT_START, "setup": setup, "rows": rows, "coverage": cov,
            "calendar": {"start_date": iso(0), "fire_day": FIRE_DAY, "days": day_tick(TP["ticks"]),
                         "idle_days": day_tick(TP["ticks"]) - TP["ticks"]}}
    form = {"schema": "jet_slice_reference_formulas/1", "fx6_scale": SCALE, "seed": FORMULA_SEED,
            **formula_cases(FORMULA_SEED), **v24_cases(FORMULA_SEED), "calendar": calendar_cases()}
    setup_cb, rows_cb = run_trajectory(TRAJ_SEED, "CB")
    cov_cb = coverage_cb(rows_cb)
    traj_cb = dict(traj, schema="jet_slice_reference_trajectory_cb/1", rule="C-B v2.4 r1 (contract 4.1, 4.1a, 4.1b)",
                   cb_params=cb_prm(), cb_fixture={"planned": sorted(PLANNED), **TP_CB,
                                                   "v_exp": "rate*labour of a known PRC (fixture)",
                                                   "tooling_takes_rest": "none (fixed A21 investment)"},
                   setup=setup_cb, rows=rows_cb, coverage=cov_cb)
    cov = dict(cov, **{"cb." + k: v for k, v in cov_cb.items()})
    return {"formulas.json": dumps(form), "trajectory.json": dumps(traj), "trajectory.csv": trajectory_csv(rows),
            "trajectory_cb.json": dumps(traj_cb), "trajectory_cb.csv": trajectory_cb_csv(rows_cb)}, cov


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--find-seed", action="store_true")
    args = ap.parse_args()
    if args.find_seed:
        for s in range(1, 200):
            _, rows = run_trajectory(s)
            if all(coverage(rows).values()):
                print(s)
                return 0
        print("none")
        return 1
    files, cov = build()
    outdir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")
    bad = [k for k, v in cov.items() if not v]
    if args.check:
        diff = []
        for name, text in files.items():
            path = os.path.join(outdir, name)
            if not os.path.exists(path) or open(path, encoding="ascii").read() != text:
                diff.append(name)
        print("check:", "OK" if not diff and not bad else "DIFF %s uncovered %s" % (diff, bad))
        return 1 if diff or bad else 0
    os.makedirs(outdir, exist_ok=True)
    for name, text in files.items():
        with open(os.path.join(outdir, name), "w", encoding="ascii", newline="\n") as f:
            f.write(text)
        print("%s sha256=%s" % (name, hashlib.sha256(text.encode()).hexdigest()))
    print("coverage:", cov)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
