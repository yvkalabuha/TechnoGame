def formula_cases(seed):
    out = {"culture_H": [], "production_profile": [], "knowledge": [], "k_ind": [], "hazard": [],
           "prob_check": [], "draws": [], "workforce_split": [], "counter_rng": []}
    for name, note, inp in CULTURE_CASES:
        out["culture_H"].append({"name": name, "note": note, "input": inp, "output": culture_step(inp)})
    for name, note, procs in PROFILE_CASES:
        case = {"procs": procs, "eps": fx("0.01")}
        out["production_profile"].append({"name": name, "note": note, "input": case,
                                          "output": production_profile(case)})
    # c_eff and progress (spec 3.1); c_money = c_n * 12 * S_ref (A9)
    for name, kw in [
        ("plain", dict(c_money=fx("1.2"), k_diff=fx("0.5"), known_elsewhere=False, k_K=ONE, Kmix=ZERO, K_ref=ONE, informs_w_known=[])),
        ("known_elsewhere", dict(c_money=fx("1.2"), k_diff=fx("0.5"), known_elsewhere=True, k_K=ONE, Kmix=ZERO, K_ref=ONE, informs_w_known=[])),
        ("kmix_and_informs", dict(c_money=fx("3.6"), k_diff=fx("0.5"), known_elsewhere=True, k_K=ONE, Kmix=fx("0.7"), K_ref=ONE, informs_w_known=[fx("0.3"), fx("0.6")])),
    ]:
        ce = c_eff(**kw)
        alloc = fx("0.14")
        out["knowledge"].append({"name": name, "input": kw, "c_eff": ce, "alloc": alloc, "dprog": div(alloc, ce)})
    th, hm, yh = fx("0.6"), fx("0.08"), fx("0.5")
    for name, prog, tick, node in [("below_threshold", "0.59", 5, 17), ("at_threshold_h0", "0.6", 5, 17),
                                   ("mid", "1.1", 7, 17), ("at_cap", "3", 9, 19), ("mid_other_node", "1.1", 7, 23),
                                   ("given_u_zero_hit", "1.1", None, 17), ("given_u_max_miss", "3", None, 17)]:
        if tick is None:   # explicitly given NextU64 values, independent of the RNG port
            u = 0 if name.endswith("hit") else M64
        else:
            u = next_u64(seed, tick, SYS_KNOW, 0 * 64 + node, 0)
        out["hazard"].append({"name": name, "key": {"seed": seed, "tick": tick, "system": SYS_KNOW,
                                                    "entity": node, "n": 0},
                              "prog": fx(prog), "theta_start": th, "h_max": hm, "y_half": yh,
                              "output": hazard(fx(prog), th, hm, yh, u)})
    ki = dict(eta=fx("0.01"), V_ref=fx("1000"), theta_ind=fx("0.25"), delta_ind=fx("0.003"))
    for name, K_ind, K_d, V_d in [("idle_decay", "0.05", "0.5", "0"), ("grow", "0.02", "0.5", "1000"),
                                  ("saturated_room_zero", "0.2", "0.5", "1000"), ("kd_zero", "0", "0", "500"),
                                  ("cap_floors_to_zero", "0", "0.000003", "500"), ("cap_one_raw", "0", "0.000004", "500")]:
        out["k_ind"].append({"name": name, "input": dict(K_ind=fx(K_ind), K_d=fx(K_d), V_d=fx(V_d), **ki),
                             "output": k_ind_step(fx(K_ind), fx(K_d), fx(V_d), **ki)})
    for p in ["0", "0.000001", "0.08", "0.5", "1"]:
        for u in [0, (fx("0.5") * TWO53 // SCALE) << 11, M64]:
            out["prob_check"].append({"p_raw": fx(p), **prob_check(u, fx(p))})
    for t in range(3):
        u = next_u64(seed, 0, SYS_AI, t, 0)
        out["draws"].append({"kind": "profile", "key": [seed, 0, SYS_AI, t, 0], "u": u, "value": draw_profile(u)})
        u = next_u64(seed, 12 * t, SYS_PRIO_J, 17, 0)
        out["draws"].append({"kind": "j", "key": [seed, 12 * t, SYS_PRIO_J, 17, 0], "u": u, "value": draw_j(u)})
        u = next_u64(seed, t, SYS_EVT_DIS, 2, 1)
        out["draws"].append({"kind": "uniform_6_18", "key": [seed, t, SYS_EVT_DIS, 2, 1], "u": u,
                             "value": draw_uniform_int(u, 6, 18)})
    for u in [0, M64]:
        out["draws"].append({"kind": "edges", "u": u, "profile": draw_profile(u), "j": draw_j(u),
                             "uniform_6_18": draw_uniform_int(u, 6, 18)})
    for name, avail, reqs in [("enough", 100, [(0, 1, 7, 30), (0, 1, 3, 40)]),
                              ("short_remainder", 10, [(0, 1, 9, 5), (0, 1, 2, 5), (0, 1, 4, 5)]),
                              ("short_uneven", 7, [(0, 1, 1, 10), (0, 1, 2, 1)])]:
        out["workforce_split"].append({"name": name, "avail": avail, "requests": reqs,
                                       "output": workforce_split(avail, reqs)})
    for v in RNG_VECTORS:
        out["counter_rng"].append({"key": list(v[:5]), "u": v[5]})
    return out


