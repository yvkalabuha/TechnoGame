# Kernel tick = 1 day (ADR-0006). Slice systems are monthly: they fire on day 1 of each calendar
# month. Month index m (0 = 1945-09) is what the spec calls "tick t"; day tick d counts days from
# START_DATE (d = 0 is 1945-09-01). Integer proleptic Gregorian arithmetic (H. Hinnant's
# days_from_civil / civil_from_days); cross-checked against datetime in build().
START_DATE = (1945, 9, 1)
FIRE_DAY = 1


def days_from_civil(y, m, d):
    y -= m <= 2
    era = (y if y >= 0 else y - 399) // 400
    yoe = y - era * 400
    doy = (153 * (m + (-3 if m > 2 else 9)) + 2) // 5 + d - 1
    doe = yoe * 365 + yoe // 4 - yoe // 100 + doy
    return era * 146097 + doe - 719468


def civil_from_days(z):
    z += 719468
    era = (z if z >= 0 else z - 146096) // 146097
    doe = z - era * 146097
    yoe = (doe - doe // 1460 + doe // 36524 - doe // 146096) // 365
    y = yoe + era * 400
    doy = doe - (365 * yoe + yoe // 4 - yoe // 100)
    mp = (5 * doy + 2) // 153
    d = doy - (153 * mp + 2) // 5 + 1
    m = mp + (3 if mp < 10 else -9)
    return y + (m <= 2), m, d


_D0 = days_from_civil(*START_DATE)


def month_ym(m):
    k = START_DATE[1] - 1 + m
    return START_DATE[0] + k // 12, k % 12 + 1


def day_tick(m):
    """Day tick at which the monthly systems of month index m fire (day FIRE_DAY of that month)."""
    y, mo = month_ym(m)
    return days_from_civil(y, mo, FIRE_DAY) - _D0


def month_fired_at(d):
    """Month index whose monthly systems fire at day tick d, or None (clock-only day)."""
    y, mo, dd = civil_from_days(_D0 + d)
    if dd != FIRE_DAY:
        return None
    return (y - START_DATE[0]) * 12 + (mo - START_DATE[1])


def iso(d):
    return "%04d-%02d-%02d" % civil_from_days(_D0 + d)


