# new
# --------------------------------------------------------------------------

def next_id(t: ItemType, items: list[Item]) -> str:
    nums = [int(re.sub(r"\D", "", i.id) or 0) for i in items if i.type is t]
    if t.prefix == "MS":  # milestones start at MS-M0
        return f"MS-M{max(nums) + 1 if nums else 0}"
    return f"{t.prefix}-{max(nums, default=0) + 1:04d}"


def slugify(title: str) -> str:
    # ASCII slug for file names; Cyrillic titles fall back to the ID only.
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return slug[:50]


def cmd_new(args) -> int:
    prefix = args.type.upper()
    if prefix not in TYPES:
        print(f"unknown type {prefix}; use one of {list(TYPES)}")
        return 2
    t = TYPES[prefix]
    items = load_items([])
    new_id = next_id(t, items)
    template = ROOT / "development" / "templates" / t.template
    text = template.read_text(encoding="utf-8")
    # JSON string = valid YAML scalar, safe for titles with ':' or quotes.
    text = (text.replace("{{ID}}", new_id)
                .replace("{{TITLE_YAML}}", json.dumps(args.title, ensure_ascii=False))
                .replace("{{TITLE}}", args.title)
                .replace("{{DATE}}", dt.date.today().isoformat()))
    slug = slugify(args.slug or args.title)
    name = f"{new_id}-{slug}.md" if slug else f"{new_id}.md"
    path = ROOT / t.folder / name
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        print(f"{rel(path)} already exists")
        return 1
    path.write_text(text, encoding="utf-8")
    print(rel(path))
    return 0


