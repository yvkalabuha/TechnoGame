# list / index
# --------------------------------------------------------------------------

def sort_key(it: Item):
    return (list(TYPES).index(it.type.prefix), it.id)


def cmd_list(args) -> int:
    items = load_items([])
    for it in sorted(items, key=sort_key):
        if args.type and it.type.prefix != args.type.upper():
            continue
        if args.status and it.meta.get("status") != args.status.upper():
            continue
        print(f"{it.id:10} {str(it.meta.get('status')):15} {it.meta.get('title')}  [{rel(it.path)}]")
    return 0


def md_link(it: Item, base: Path) -> str:
    target = Path(*([".."] * len(base.relative_to(ROOT).parts))) / rel(it.path) \
        if base != ROOT else Path(rel(it.path))
    return f"[{it.id}]({target.as_posix()})"


def render_backlog(items: list[Item]) -> str:
    base = BACKLOG.parent
    lines = [GENERATED_NOTE, "", "# BACKLOG", "",
             "Сводка всех элементов реестра. Источник — frontmatter файлов.", ""]
    titles = {"MS": "Milestones", "TASK": "Задачи", "HYP": "Гипотезы",
              "EXP": "Эксперименты", "ADR": "ADR", "RR": "Research Reports"}
    for prefix, title in titles.items():
        group = sorted((i for i in items if i.type.prefix == prefix), key=sort_key)
        lines += [f"## {title}", ""]
        if not group:
            lines += ["_нет_", ""]
            continue
        extra = {"TASK": "milestone", "EXP": "hypothesis"}.get(prefix)
        header = "| ID | Статус | Название |" + (f" {extra} |" if extra else "")
        lines += [header, "|---|---|---|" + ("---|" if extra else "")]
        for it in group:
            row = f"| {md_link(it, base)} | {it.meta.get('status')} | {it.meta.get('title')} |"
            if extra:
                row += f" {it.meta.get(extra, '')} |"
            lines.append(row)
        lines.append("")
    return "\n".join(lines)


ACTIVE_STATUSES = ["IN_PROGRESS", "REVIEW", "BLOCKED", "APPROVED"]


def render_active(items: list[Item]) -> str:
    active = [i for i in items if i.type.prefix == "TASK"
              and i.meta.get("status") in ACTIVE_STATUSES]
    active.sort(key=lambda i: (ACTIVE_STATUSES.index(i.meta["status"]), i.id))
    if not active:
        return "_нет активных задач_"
    return "\n".join(f"- {i.id} [{i.meta['status']}] {i.meta.get('title')} "
                     f"({i.meta.get('agent')})" for i in active)


def replace_active_block(text: str, items: list[Item]) -> str:
    pattern = re.compile(re.escape(ACTIVE_START) + r".*?" + re.escape(ACTIVE_END), re.S)
    block = f"{ACTIVE_START}\n{render_active(items)}\n{ACTIVE_END}"
    return pattern.sub(lambda _: block, text, count=1)


def cmd_index(_args) -> int:
    errors: list[str] = []
    items = load_items(errors)
    BACKLOG.write_text(render_backlog(items), encoding="utf-8")
    if CURRENT_STATE.exists():
        text = CURRENT_STATE.read_text(encoding="utf-8")
        if ACTIVE_START in text:
            CURRENT_STATE.write_text(replace_active_block(text, items), encoding="utf-8")
    print(f"index written ({len(items)} items)")
    for e in errors:
        print("  warning:", e)
    return 0


