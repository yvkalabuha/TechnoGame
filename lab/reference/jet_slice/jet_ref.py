# Slice spec 9.1 streams (system ids).
SYS_KNOW, SYS_PRIO_J, SYS_EVT_DIS, SYS_EVT_LIC, SYS_AI, SYS_START = 1, 2, 3, 4, 5, 6
TWO53 = 1 << 53


def prob_threshold(p_raw):
    """ADR-0003 R2: floor(p_raw * 2^53 / 10^6), Int128."""
    return (p_raw * TWO53) // SCALE


def prob_check(u, p_raw):
    r = u >> 11
    thr = prob_threshold(p_raw)
    return {"u": u, "r": r, "threshold": thr, "hit": r < thr}


def draw_profile(u):
    return ((u >> 11) * 3) >> 53                         # spec 9.2: floor(3U)


def draw_j(u):
    return 500_000 + (((u >> 11) * 1_000_001) >> 53)     # spec 9.2: j in [0.5; 1.5] Fx6


def draw_uniform_int(u, lo, hi):
    return lo + (((u >> 11) * (hi - lo + 1)) >> 53)      # spec 9.2


# ---------------------------------------------------------------- contract 4.1: culture_H step
def culture_step(i):
    """One cell culture_H[site,c,d]. Input dict (all Fx6 raw unless noted):
    H, Hcap, phi_floor, alpha, k_qp, qp_active(bool), d_is_qc(bool), act, act_norm, w,
    k_catch, sigma, rho_max, delta_H,
    procs: [{prc_id, v, r_d, world_lead(bool)}]  (v = 0 or the process is absent when yield_p = 0),
    spill_in: [{cluster, R, H_other}]  (same d, other clusters c' of the site, snapshot values).
    """
    H = i["H"]
    procs = sorted(i["procs"], key=lambda p: p["prc_id"])
    V = add(*[p["v"] for p in procs]) if procs else 0
    out = {"V_c": V, "s_p": []}
    drive = catch = maint = ZERO
    if V != 0:
        act_ratio = min(ONE, div(i["act"], i["act_norm"]))
        for p in procs:
            s = div(p["v"], V)
            above = max(ZERO, add(p["r_d"], fx("0.25"), -H))
            drive = add(drive, mul(s, above))
            if p["world_lead"]:
                catch = add(catch, mul(s, above))   # world_lead in {0,1}: multiply == select
            maint = add(maint, mul(mul(s, p["r_d"]), act_ratio))
            out["s_p"].append({"prc_id": p["prc_id"], "s": s})
    spill = ZERO
    for sp in sorted(i["spill_in"], key=lambda x: x["cluster"]):
        spill = add(spill, mul(sp["R"], max(ZERO, sp["H_other"] - H)))
    H_floor = mul(i["phi_floor"], i["Hcap"])
    sat = max(ZERO, ONE - div(H, i["Hcap"]))
    alpha_eff = mul(i["alpha"], ONE + i["k_qp"]) if (i["qp_active"] and i["d_is_qc"]) else i["alpha"]
    inner = add(mul(mul(mul(alpha_eff, i["act"]), i["w"]), drive),
                mul(i["k_catch"], catch),
                mul(i["sigma"], spill))
    dH_plus = mul(sat, inner)
    dH_minus = mul(i["delta_H"], max(ZERO, H - max(maint, H_floor)))
    H_new = add(H, min(dH_plus, i["rho_max"]), -dH_minus)
    out.update({"drive": drive, "catch": catch, "maint": maint, "spill": spill, "H_floor": H_floor,
                "sat": sat, "alpha_eff": alpha_eff, "dH_plus": dH_plus,
                "dH_plus_capped": min(dH_plus, i["rho_max"]), "dH_minus": dH_minus, "H_new": H_new})
    return out


# ---------------------------------------------------------------- contract 4.2: yield and production_profile
DIMS = ["precision", "purity", "quality_control"]        # fixed order = product order (A1)


def g_gap(gap):
    if gap < fi(-1):
        return ZERO
    if gap < ZERO:
        t = ONE + gap
        return mul(t, t)
    return ONE


def ramp(X, Xh, lam0):
    return add(lam0, div(mul(ONE - lam0, X), add(X, Xh)))   # spec 3.2, left to right


def yield_p(p):
    """p: {prc_id, req{dim: Fx6|None}, H{dim}, M{dim}, X, Xh, lam0, l_lic(Fx6|None)}."""
    dims = []
    acc = ONE
    for d in DIMS:
        r = p["req"].get(d)
        if r is None or r <= 0:
            continue
        c = min(p["H"][d], p["M"][d])
        src = "H" if p["H"][d] <= p["M"][d] else "M"      # tie H = M -> H (spec 3.5 A5)
        g = g_gap(c - r)
        acc = mul(acc, g)
        dims.append({"dim": d, "c_d": c, "src": src, "gap": c - r, "g": g})
    Xh = p["Xh"] if p.get("l_lic") is None else mul(p["Xh"], ONE - p["l_lic"])
    rp = ramp(p["X"], Xh, p["lam0"])
    # contract 4.2 A4: q_p = g(c_qc - r_qc) if r_qc > 0, else 1
    q_p = next((d["g"] for d in dims if d["dim"] == "quality_control"), ONE)
    return {"prc_id": p["prc_id"], "dims": dims, "Xh_eff": Xh, "ramp": rp, "yield": mul(acc, rp), "q_p": q_p}


def production_profile(case):
    """case: {procs: [yield_p input + n_p (Fx6), base_cost (Fx6), known(bool)], eps}."""
    rows = [dict(yield_p(p), n_p=p["n_p"], base_cost=p["base_cost"], known=p["known"])
            for p in sorted(case["procs"], key=lambda p: p["prc_id"])]
    eps = case["eps"]
    admitted = all(r["yield"] > 0 and r["known"] for r in rows)
    num = den = ZERO
    for r in rows:
        r["yc"] = max(r["yield"], eps)
        nb = mul(r["n_p"], r["base_cost"])
        num = add(num, div(nb, r["yc"]))
        den = add(den, nb)
    ucm = div(num, den)
    bn = min(rows, key=lambda r: (r["yield"], r["prc_id"]))
    if bn["dims"] and min(d["g"] for d in bn["dims"]) < ONE:
        bd = min(bn["dims"], key=lambda d: (d["g"], DIMS.index(d["dim"])))
        bottleneck = {"prc": bn["prc_id"], "dim": bd["dim"], "src": bd["src"]}
    else:
        bottleneck = {"prc": bn["prc_id"], "dim": None, "src": "ramp"}   # spec 3.5 A5
    return {"per_process": rows, "admitted": admitted, "unit_cost_mult": ucm,
            "bottleneck": bottleneck, "q": min(r["q_p"] for r in rows)}   # contract 4.2 A4


# ---------------------------------------------------------------- slice spec 3.1: knowledge
def c_eff(c_money, k_diff, known_elsewhere, k_K, Kmix, K_ref, informs_w_known):
    num = mul(c_money, ONE - mul(k_diff, ONE if known_elsewhere else ZERO))
    den = mul(ONE + div(mul(k_K, Kmix), K_ref), ONE + add(*informs_w_known) if informs_w_known else ONE)
    return div(num, den)


def hazard(prog, theta, h_max, y_half, u):
    """Spec 3.1: only when prog >= theta. h = h_max*y/(y+y_half), left to right."""
    if prog < theta:
        return {"active": False, "y": None, "h": ZERO, "check": None, "opened": False}
    y = prog - theta
    h = div(mul(h_max, y), add(y, y_half))
    chk = prob_check(u, h)
    return {"active": True, "y": y, "h": h, "check": chk, "opened": chk["hit"]}


def k_ind_step(K_ind, K_d, V_d, eta, V_ref, theta_ind, delta_ind):
    """Contract 4.3 (canonical form, 4.0). Guard (contract v2.1 + slice spec v0.6 3.5 A16): no growth
    when K_d = 0 or when cap = theta_ind*K_d floors to 0 raw (the division would be by zero)."""
    if V_d == 0:
        return {"branch": "decay", "cap": None, "frac": None, "K_ind_new": K_ind - mul(delta_ind, K_ind)}
    cap = mul(theta_ind, K_d)
    if K_d == 0 or cap == 0:
        return {"branch": "no_cap", "cap": cap, "frac": None, "K_ind_new": K_ind}
    frac = div(mul(eta, V_d), add(V_d, V_ref))
    return {"branch": "grow", "cap": cap, "frac": frac,
            "K_ind_new": add(K_ind, mul(frac, max(ZERO, ONE - div(K_ind, cap))))}


# ---------------------------------------------------------------- contract 4.6: reserve_workforce split
def workforce_split(avail, requests):
    """requests: [(site, cat, requester_id, n)] for one (site, cat); integer people."""
    reqs = sorted(requests, key=lambda r: (r[0], r[1], r[2]))
    total = sum(r[3] for r in reqs)
    if total <= avail:
        return [{"requester_id": r[2], "n": r[3], "granted": r[3]} for r in reqs]
    granted = [(r[3] * avail) // total for r in reqs]
    rest = avail - sum(granted)
    for k in range(len(reqs)):                 # remainder one by one in requester_id order
        if rest == 0:
            break
        if granted[k] < reqs[k][3]:
            granted[k] += 1
            rest -= 1
    return [{"requester_id": r[2], "n": r[3], "granted": g} for r, g in zip(reqs, granted)]


