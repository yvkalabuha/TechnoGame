# ---------------------------------------------------------------- Fx6 (mirror of Kernel/Fx6.cs)
SCALE = 1_000_000
I64_MIN, I64_MAX = -(1 << 63), (1 << 63) - 1
ONE = SCALE
ZERO = 0


def _chk(x):
    if not I64_MIN <= x <= I64_MAX:
        raise OverflowError(x)
    return x


def fx(s):
    """Exact decimal string -> raw Fx6. Refuses more than 6 fractional digits (no silent rounding)."""
    s = str(s).strip()
    neg = s.startswith("-")
    if neg:
        s = s[1:]
    whole, _, frac = s.partition(".")
    if len(frac) > 6:
        raise ValueError("more than 6 fractional digits: " + s)
    raw = int(whole or "0") * SCALE + int((frac + "000000")[:6])
    return _chk(-raw if neg else raw)


def fi(n):
    return _chk(n * SCALE)


def mul(a, b):
    return _chk((a * b) // SCALE)          # Python // floors, same as Fx6.FloorDiv


def div(a, b):
    if b == 0:
        raise ZeroDivisionError
    return _chk((a * SCALE) // b)


def add(*xs):
    return _chk(sum(xs))


def dec(raw):
    sign = "-" if raw < 0 else ""
    a = abs(raw)
    return "%s%d.%06d" % (sign, a // SCALE, a % SCALE)


# ---------------------------------------------------------------- CounterRng (mirror of Kernel/CounterRng.cs)
M64 = (1 << 64) - 1
M32 = (1 << 32) - 1
SALTS = [0x6A09E667F3BCC908, 0xBB67AE8584CAA73B, 0x3C6EF372FE94F82B,
         0xA54FF53A5F1D36F1, 0x510E527FADE682D1]


def _mix(x):
    z = (x + 0x9E3779B97F4A7C15) & M64
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M64
    return z ^ (z >> 31)


def next_u64(seed, tick, system, entity, n):
    h = _mix((seed & M64) ^ SALTS[0])
    h = _mix(h ^ (tick & M64) ^ SALTS[1])
    h = _mix(h ^ (system & M32) ^ SALTS[2])
    h = _mix(h ^ (entity & M32) ^ SALTS[3])
    return _mix(h ^ (n & M32) ^ SALTS[4])


